DROP TABLE IF EXISTS salary_slip;
DROP TABLE IF EXISTS contract;
DROP TABLE IF EXISTS daily_report;
DROP TABLE IF EXISTS leave_request;
DROP TABLE IF EXISTS announcement;
DROP TABLE IF EXISTS attendance;
